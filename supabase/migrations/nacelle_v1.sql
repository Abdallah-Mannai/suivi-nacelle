-- --- profils -------------------------------------------------
-- Chacun se voit ; l'admin voit tout et est SEUL a ecrire.
DROP POLICY IF EXISTS profils_select ON profils;
CREATE POLICY profils_select ON profils FOR SELECT TO authenticated
  USING (id = auth.uid() OR est_admin());

DROP POLICY IF EXISTS profils_insert ON profils;
CREATE POLICY profils_insert ON profils FOR INSERT TO authenticated
  WITH CHECK (est_admin());

DROP POLICY IF EXISTS profils_update ON profils;
CREATE POLICY profils_update ON profils FOR UPDATE TO authenticated
  USING (est_admin()) WITH CHECK (est_admin());

DROP POLICY IF EXISTS profils_delete ON profils;
CREATE POLICY profils_delete ON profils FOR DELETE TO authenticated
  USING (est_admin());

-- --- tournees ------------------------------------------------
-- Le nacelliste ne voit et ne gere que SES tournees ; l'admin tout.
DROP POLICY IF EXISTS tournees_select ON tournees;
CREATE POLICY tournees_select ON tournees FOR SELECT TO authenticated
  USING (nacelliste_id = auth.uid() OR est_admin());

DROP POLICY IF EXISTS tournees_insert ON tournees;
CREATE POLICY tournees_insert ON tournees FOR INSERT TO authenticated
  WITH CHECK (nacelliste_id = auth.uid() OR est_admin());

DROP POLICY IF EXISTS tournees_update ON tournees;
CREATE POLICY tournees_update ON tournees FOR UPDATE TO authenticated
  USING (nacelliste_id = auth.uid() OR est_admin())
  WITH CHECK (nacelliste_id = auth.uid() OR est_admin());

DROP POLICY IF EXISTS tournees_delete ON tournees;
CREATE POLICY tournees_delete ON tournees FOR DELETE TO authenticated
  USING (nacelliste_id = auth.uid() OR est_admin());

-- --- interventions -------------------------------------------
-- Visibles/modifiables uniquement via la propriete de la tournee.
DROP POLICY IF EXISTS interventions_select ON interventions;
CREATE POLICY interventions_select ON interventions FOR SELECT TO authenticated
  USING (tournee_est_a_moi(tournee_id) OR est_admin());

DROP POLICY IF EXISTS interventions_insert ON interventions;
CREATE POLICY interventions_insert ON interventions FOR INSERT TO authenticated
  WITH CHECK (tournee_est_a_moi(tournee_id) OR est_admin());

DROP POLICY IF EXISTS interventions_update ON interventions;
CREATE POLICY interventions_update ON interventions FOR UPDATE TO authenticated
  USING (tournee_est_a_moi(tournee_id) OR est_admin())
  WITH CHECK (tournee_est_a_moi(tournee_id) OR est_admin());

DROP POLICY IF EXISTS interventions_delete ON interventions;
CREATE POLICY interventions_delete ON interventions FOR DELETE TO authenticated
  USING (tournee_est_a_moi(tournee_id) OR est_admin());

-- --- positions -----------------------------------------------
-- ECRITURE : uniquement le nacelliste proprietaire, sur SA tournee,
-- et en son propre nom (nacelliste_id impose = auth.uid()).
DROP POLICY IF EXISTS positions_select ON positions;
CREATE POLICY positions_select ON positions FOR SELECT TO authenticated
  USING (nacelliste_id = auth.uid() OR est_admin());

DROP POLICY IF EXISTS positions_insert ON positions;
CREATE POLICY positions_insert ON positions FOR INSERT TO authenticated
  WITH CHECK (nacelliste_id = auth.uid() AND tournee_est_a_moi(tournee_id));

DROP POLICY IF EXISTS positions_delete ON positions;
CREATE POLICY positions_delete ON positions FOR DELETE TO authenticated
  USING (nacelliste_id = auth.uid() OR est_admin());
-- (pas d'UPDATE : une position ne se modifie pas, elle se remplace)

-- --- parametres ----------------------------------------------
-- Lisibles par tous les connectes (le nacelliste a besoin du temps
-- d'intervention et des textes par defaut) ; modifiables par l'admin.
DROP POLICY IF EXISTS parametres_select ON parametres;
CREATE POLICY parametres_select ON parametres FOR SELECT TO authenticated
  USING (TRUE);

DROP POLICY IF EXISTS parametres_update ON parametres;
CREATE POLICY parametres_update ON parametres FOR UPDATE TO authenticated
  USING (est_admin()) WITH CHECK (est_admin());

DROP POLICY IF EXISTS parametres_insert ON parametres;
CREATE POLICY parametres_insert ON parametres FOR INSERT TO authenticated
  WITH CHECK (est_admin());


